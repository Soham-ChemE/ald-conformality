"""Generate a self-contained JSL (data embedded as a New Table literal, no file import, which stalls JMP headless)
that fits response surfaces to the DOE and writes figures/doe_rsm_report.txt."""
import pandas as pd
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
d = pd.read_csv(ROOT / "figures/doe_results.csv")
cols = ["c_x", "c_Q", "c_p", "c_g", "t90_worst", "edge_lag_pct", "utilization"]
def vals(c): return "{" + ", ".join(f"{v:.6g}" for v in d[c]) + "}"
newcols = ",\n    ".join(f'New Column( "{c}", Numeric, Continuous, Values( {vals(c)} ) )' for c in cols)
jsl = f'''// Generated by analysis/make_doe_jsl.py from figures/doe_results.csv ({len(d)} runs). Do not edit by hand.
root = "{ROOT}/";
out = "";
Try(
    dt = New Table( "doe", Invisible,
    {newcols}
    );
    dt << New Column( "log10_t90_worst", Numeric, Continuous, Formula( Log10( :t90_worst ) ) );
    dt << Run Formulas;
    out = "JMP " || JMP Version() || " response-surface fits, " || Char( N Rows( dt ) ) || " runs (face-centred CCD, coded factors)\\!n";
    responses = {{"log10_t90_worst", "edge_lag_pct", "utilization"}};
    For( i = 1, i <= N Items( responses ), i++,
        rname = responses[i];
        fit = dt << Fit Model( Y( Column( dt, rname ) ), Effects( :c_x & RS, :c_Q & RS, :c_p & RS, :c_g & RS ),
            Personality( "Standard Least Squares" ), Emphasis( "Minimal Report" ), Run );
        rep = fit << Report;
        sof = rep[Outline Box( "Summary of Fit" )][Number Col Box( 1 )] << Get;
        pe = rep[Outline Box( "Parameter Estimates" )];
        terms = pe[String Col Box( 1 )] << Get; est = pe[Number Col Box( 1 )] << Get; pval = pe[Number Col Box( 4 )] << Get;
        out = out || "\\!n== " || rname || ": RSquare " || Char( Round( sof[1], 4 ) ) || ", RSquare Adj " || Char( Round( sof[2], 4 ) ) || ", RMSE " || Char( Round( sof[3], 4 ) ) || "\\!n";
        For( j = 1, j <= N Items( terms ), j++, out = out || "   " || terms[j] || " = " || Char( Round( est[j], 5 ) ) || "   (p = " || Char( Round( pval[j], 4 ) ) || ")\\!n" );
        fit << Save Prediction Formula;
        rep << Close Window;
    );
    dt << Save( root || "figures/doe_results_with_predictions.jmp" );
    Save Text File( root || "figures/doe_rsm_report.txt", out );
    Close( dt, No Save );
,
    Save Text File( root || "figures/doe_rsm_error.txt", "JSL error: " || Char( exception_msg ) || "\\!n\\!nPartial output:\\!n" || out );
);
Quit( No Save );
'''
(ROOT / "analysis/doe_rsm.jsl").write_text(jsl); print("wrote analysis/doe_rsm.jsl with", len(d), "rows")
